import { useState } from 'react';
import { Link } from 'react-router-dom';
import { AlertTriangle, BellOff, BellRing, Clock } from 'lucide-react';
import { useData } from '../context/DataContext';
import { ALERT_CATEGORY_LABEL, ALERT_RULES, DATASETS, KIND_LABEL, LOCATIONS, getLocation, getSource } from '../config';
import { formatDateTime } from '../lib/time';
import { KindBadge } from '../components/Badges';
import { EmptyState, ErrorState, Loading } from '../components/States';
import type { AlertCategory, AlertStatus } from '../types';

const STATUS_TEXT: Record<AlertStatus, string> = {
  active: 'Active',
  expired: 'Expired',
  suppressed_stale: 'Not current: data stale',
};

export default function Alerts() {
  const { status, bundle, events, staleKeys, setLocationId, error, reload } = useData();
  const [filter, setFilter] = useState('all');
  const [category, setCategory] = useState<'all' | AlertCategory>('all');
  const [showExpired, setShowExpired] = useState(false);

  if (status === 'loading' && !bundle) return <div className="container section"><Loading /></div>;
  if (!bundle) return <div className="container section"><ErrorState message={error ?? 'Unknown error'} onRetry={reload} /></div>;

  const list = events.filter((e) => (filter === 'all' || e.locationId === filter) && (category === 'all' || e.category === category) && (showExpired || e.status !== 'expired'));

  return (
    <div className="container section page">
      <h1>Location-based alerts</h1>
      <p className="lead">
        In-app advisories generated by documented rules against validated data. They are informational and are <strong>not official warnings</strong>.
      </p>

      {staleKeys.length > 0 && (
        <div className="notice notice-warn" role="alert">
          <AlertTriangle size={18} aria-hidden />
          <div><strong>Data-quality warning.</strong> One or more feeds are stale. Alerts that depend on them are shown as “not current” and are not presented as active.</div>
        </div>
      )}

      <div className="toolbar">
        <label>Location{' '}
          <select value={filter} onChange={(e) => setFilter(e.target.value)}>
            <option value="all">All locations</option>
            {LOCATIONS.map((l) => <option key={l.id} value={l.id}>{l.name}</option>)}
          </select>
        </label>
        <label>Type{' '}
          <select value={category} onChange={(e) => setCategory(e.target.value as 'all' | AlertCategory)}>
            <option value="all">All alert types</option>
            {(Object.keys(ALERT_CATEGORY_LABEL) as AlertCategory[]).map((c) => <option key={c} value={c}>{ALERT_CATEGORY_LABEL[c]}</option>)}
          </select>
        </label>
        <label className="check"><input type="checkbox" checked={showExpired} onChange={(e) => setShowExpired(e.target.checked)} /> Show expired alerts</label>
      </div>

      {list.length === 0 ? (
        <EmptyState title="No alerts to show">No rule has triggered for this selection within the validity window.</EmptyState>
      ) : (
        <ul className="alert-list">
          {list.map((e) => (
            <li key={e.id} className={`alert-item st-${e.status}`}>
              <div className="alert-icon">{e.status === 'active' ? <BellRing aria-hidden /> : e.status === 'expired' ? <BellOff aria-hidden /> : <AlertTriangle aria-hidden />}</div>
              <div className="alert-body">
                <div className="alert-top">
                  <strong>{e.ruleName}</strong>
                  {e.category && <span className="badge">{ALERT_CATEGORY_LABEL[e.category]}</span>}
                  <span className={`badge st-badge-${e.status}`}>{STATUS_TEXT[e.status]}</span>
                </div>
                <p>{getLocation(e.locationId).name}: {e.value} {e.unit} (threshold {e.threshold} {e.unit})</p>
                <dl className="alert-meta">
                  <div><dt>Trigger</dt><dd>{DATASETS.find((d) => d.key === e.datasetKey)!.label} ≥ {e.threshold} {e.unit}</dd></div>
                  <div><dt>Data type</dt><dd><KindBadge kind={e.dataKind} /></dd></div>
                  <div><dt>Source</dt><dd>{getSource(e.sourceId).name}</dd></div>
                  <div><dt>Source time</dt><dd>{formatDateTime(e.sourceTimestamp)}</dd></div>
                  <div><dt>Issued</dt><dd>{formatDateTime(e.triggeredAt)}</dd></div>
                  <div><dt>Valid until</dt><dd><Clock size={12} aria-hidden /> {formatDateTime(e.validUntil)}</dd></div>
                </dl>
                <Link to="/dashboard#map" className="inline-link" onClick={() => setLocationId(e.locationId)}>View location on map</Link>
              </div>
            </li>
          ))}
        </ul>
      )}

      <h2>Alert rules</h2>
      <div className="table-scroll">
        <table>
          <thead><tr><th>Rule</th><th>Type</th><th>Condition</th><th>Suppression window</th><th>Valid for</th><th>Review status</th></tr></thead>
          <tbody>
            {ALERT_RULES.map((r) => (
              <tr key={r.id}>
                <td>{r.name}</td>
                <td>{ALERT_CATEGORY_LABEL[r.category ?? 'weather']}</td>
                <td>{DATASETS.find((d) => d.key === r.datasetKey)!.label} {r.operator} {r.threshold} {r.unit}</td>
                <td>{r.suppressionHours} h</td>
                <td>{r.validityHours} h</td>
                <td>{r.reviewStatus}</td>
              </tr>
            ))}
          </tbody>
        </table>
      </div>
      <p className="muted">
        Rules ignore missing values and forecasts. A repeat trigger inside the suppression window does not create a new alert. Thresholds shown are placeholders
        and must be reviewed by a qualified marine or meteorological specialist before any pilot ({KIND_LABEL.observation.toLowerCase()} data preferred where available).
      </p>
    </div>
  );
}
